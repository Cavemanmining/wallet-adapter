def test_an_action_event_reaches_a_transport_through_the_real_alert_service():
    """The one seam where two packages' signatures must agree exactly.

    ``Supervisor._publish`` calls ``publish(profile, kind, title, body,
    data=, priority=, dedupe_key=)``.  A fake with a loose signature would
    accept anything; the real service would not, and the failure would be
    swallowed into ``last_alert_error`` and never seen.
    """
    alerts = pytest.importorskip("jarvis_alerts")
    from jarvis_alerts.outbox import no_jitter

    clock = Clock()
    store = alerts.MemoryStore(clock)
    service = alerts.AlertService(store, clock,
                                  id_source=lambda: f"id-{int(clock.at)}")
    store.register(alerts.Subscription(
        profile_id="owner", device_id="phone", transport="fake",
        blob="fake://phone", created_at=clock.at,
    ))
    transport = alerts.FakeTransport()
    worker = alerts.Worker(store, {"fake": transport}, clock, no_jitter)

    bot = ScriptedBot(clock, "poke", [
        [(Severity.ACTION, "k", None)],
        [(Severity.ACTION, "k", None)],     # the same question: no second push
        [(Severity.NOTICE, "k", True)],     # a resolution is below the threshold
    ])
    sup = Supervisor(BotRegistry([bot]), clock, alerts=service)

    delivered = 0
    for _ in range(3):
        sup.run_round(clock.at)
        delivered += worker.run_once().delivered
        clock.advance(600.0)

    assert sup.last_alert_error == "", sup.last_alert_error
    assert delivered == 1, "one open question is one push"
    assert transport.calls_for("owner", "phone") == 1


def test_an_alert_service_that_is_down_does_not_fail_the_round():
    """contracts.py: a bot that had something to say is not punished for
    the notifier being broken, and the failure is visible rather than
    silent."""
    class Broken:
        def publish(self, *args, **kwargs):
            raise RuntimeError("notifier down")

    clock = Clock()
