def test_a_generated_bot_closes_its_own_attention(tmp_path):
    """The template's convention and the supervisor's reader, end to end.

    This is the cross-lane claim: the generator emits a bot that resolves
    its own request, and the framework -- written by a different agent
    against the same contract -- acts on it, with no app-side glue.
    """
    module = _import_generated(tmp_path, "inbox-watch")
    watched = tmp_path / "watched"
    watched.mkdir()
    for name in ("a", "b"):
        (watched / name).write_text("x", encoding="utf-8")

    clock = Clock()
    bot = module.build(clock=clock, watch_dir=str(watched), threshold=2)
    sup = Supervisor(BotRegistry([bot]), clock)
    sup.run_round(clock.at)
    assert sup.badge_status()["attention"] == 1

    (watched / "a").unlink()
    (watched / "b").unlink()
    clock.advance(3600.0)
    sup.run_round(clock.at)
    assert sup.badge_status()["attention"] == 0
    assert sup.badge_status()["state"] == "ok"


def test_the_poke_bot_closes_its_own_attention_with_no_app_side_glue():
    """``close_resolved`` was the workaround; the framework now does it.

    The helper stays -- it is harmless and an app may still drive it -- but
    a supervisor running PokeBot with nothing wired after the round must
    reach an empty badge when the deal goes away.
    """
    poke_bot = pytest.importorskip("jarvis_bots.bots.poke_bot")
