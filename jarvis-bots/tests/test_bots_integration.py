"""The seams between the lanes, exercised as one system.

Five agents wrote ``jarvis_bots``: the framework, the generator, the poke
plugin, the gate and this.  Each lane's own suite checks it against
``contracts.py``; none of them can check the thing the package actually
claims, which ``contracts.py`` states in its first paragraph -- "the point
of this module is that it [the Pokemon assistant] is not special.  Adding
the second bot should be a class and a page, not a refactor."

So what is tested here is only what needs more than one lane:

* **the package's front door** -- :mod:`jarvis_bots` re-exports a usable
  surface and no name it binds shadows a submodule, which would make
  ``from jarvis_bots import registry`` mean different things depending on
  what had been imported first;
* **the attention lifecycle across the lanes** -- the scaffold template and
  :class:`~jarvis_bots.bots.poke_bot.PokeBot` both close a request for a
  decision by re-raising the key below ACTION with
  :data:`~jarvis_bots.supervisor.RESOLVED_FLAG` set, and the supervisor
  reads it.  Before the fix this claim was an ``xfail`` in the scaffold
  suite: the badge could be filled and never emptied;
* **the platform claim, run** -- a bot generated by ``new-bot``, with no
  edit, registered beside ``PokeBot`` under one supervisor for twenty
  rounds;
* **the page contract** -- ``launcher_state`` against ``web/README.md``
  *and* against the demo dataset ``web/bots.html`` renders, so the page
  cannot drift from the supervisor in silence;
* **the delivery seam** -- a bot's ACTION event through the real
  :class:`jarvis_alerts.api.AlertService`, outbox and worker to a
  transport, which is the one path where the two packages' signatures have
  to agree exactly;
* **determinism** -- the same seed and the same clock give the same
  transcript in a separate process, under a different ``PYTHONHASHSEED``.

Nothing here sleeps, opens a socket or reads a real clock.
"""

