def _import_generated(tmp_path: Path, bot_id: str):
    """Generate a bot into ``tmp_path`` and import it, unedited."""
    import importlib.util

    dest = tmp_path / "gen"
    paths = new_bot(bot_id=bot_id, name="Stock watcher",
                    blurb="Watches a folder.", kind="radar", dest_dir=dest)
    spec = importlib.util.spec_from_file_location(paths[0].stem, paths[0])
    module = importlib.util.module_from_spec(spec)
    sys.modules[paths[0].stem] = module
    try:
        spec.loader.exec_module(module)
    finally:
        sys.modules.pop(paths[0].stem, None)
    return module


def _build_poke(poke_bot):
    """PokeBot over a scripted shop: cheap, then dearer, then sold out."""
    from jarvis_poke.catalog import Catalog
    from jarvis_poke.contracts import Budget, FetchResult, Observation, Rule, Stock
    from jarvis_poke.engine import DecisionEngine
    from jarvis_poke.prices import PriceHistory
    from jarvis_poke.rules import RuleSet
    from jarvis_poke.sources import MemoryPollStore, PollScheduler, load_policies

    clock = Clock()
    step = {"n": 0}
    catalog = Catalog.load()
    watched = [p.id for p in catalog.products()[:3]]
    rules = RuleSet(
        [Rule(product_id=pid, max_price=5500, cooldown_s=1800.0) for pid in watched],
        budget=Budget(total=50_000),
    )
    history = PriceHistory()
    engine = DecisionEngine(catalog, rules, history, clock)
    scheduler = PollScheduler(catalog, load_policies(), clock, MemoryPollStore())

    def fetcher(url, headers, policy):
        return FetchResult(ok=True, status=200, body="<fake/>")

    def parser(sku, body, at):
        n = step["n"]
        out = Stock.OUT_OF_STOCK if n >= 9 else Stock.IN_STOCK
        return Observation(
            product_id=sku.product_id, source=sku.source, sku=sku.sku, at=at,
            stock=out, price=None if out is Stock.OUT_OF_STOCK else 4200,
            shipping=0, url=sku.url,
        )

    bot = poke_bot.PokeBot(catalog, rules, history, engine, scheduler,
                           fetcher, parser, clock)
    return {"clock": clock, "bot": bot, "step": step}


def test_a_generated_bot_runs_beside_the_poke_bot(tmp_path):
    """contracts.py's opening claim, as a running system.

    Two bots written months and lanes apart, one registry, one supervisor,
    twenty rounds: both appear on the launcher with the state the
    supervisor owns, and pausing one leaves the other running.
    """
    poke_bot = pytest.importorskip("jarvis_bots.bots.poke_bot")
    module = _import_generated(tmp_path, "restock")
    watched = tmp_path / "watched"
    watched.mkdir()
    for i in range(5):
        (watched / f"f{i}").write_text("x", encoding="utf-8")

    fleet = _build_poke(poke_bot)
    clock = fleet["clock"]
    generated = module.build(clock=clock, watch_dir=str(watched), threshold=2)

    registry = BotRegistry()
    registry.register_from({"poke": fleet["bot"], "restock": generated})
    sup = Supervisor(registry, clock)
    assert registry.ids() == ["poke", "restock"]

    for r in range(20):
        sup.run_round(clock.at)
        if r == 9:
            sup.pause("restock")
        fleet["step"]["n"] += 1
        clock.advance(1800.0)

    state = sup.launcher_state(clock.at)
    cards = {c["id"]: c for c in state["bots"]}
    assert list(cards) == ["poke", "restock"], "registration order is tick order"
    assert cards["poke"]["state"] == BotState.RUNNING.ui
    assert cards["poke"]["kind"] == "cart"
    assert cards["restock"]["state"] == BotState.PAUSED.ui
    assert cards["restock"]["kind"] == "radar"
    assert cards["restock"]["attention"] == 0, "paused means no attention"
    assert sup.badge_status()["state"] == "warn"

    sup.resume("restock")
    after = {c["id"]: c["state"] for c in sup.launcher_state(clock.at)["bots"]}
    assert after == {"poke": BotState.RUNNING.ui, "restock": BotState.RUNNING.ui}
    assert sup.badge_status()["state"] == "ok"

    # Neither bot's health was touched by the other.
    assert sup.health("poke").consecutive_failures == 0
    assert sup.health("restock").consecutive_failures == 0
    assert sup.quarantined_ids() == []


