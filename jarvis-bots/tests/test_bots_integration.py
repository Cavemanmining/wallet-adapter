def test_the_cli_drives_a_two_bot_fleet_across_processes(tmp_path):
    """``pause`` that forgets itself on exit is not a pause.

    Three separate interpreters: run a round, pause a bot, read the badge.
    The third has to see the second's decision, which only works if the
    state file carries it.
    """
    pytest.importorskip("jarvis_bots.bots.poke_bot")
    wiring = tmp_path / "wiring.py"
    dest = tmp_path / "gen"
    new_bot(bot_id="restock", name="Stock watcher", blurb="Watches.",
            kind="radar", dest_dir=dest)
    wiring.write_text(
        "import sys\n"
        f"sys.path.insert(0, {str(dest)!r})\n"
        "import restock\n"
        "def BOTS(clock):\n"
        "    bot = restock.build(clock=clock, watch_dir=%r, threshold=99)\n"
        "    return {bot.info.id: bot}\n" % str(dest),
        encoding="utf-8",
    )
    state = tmp_path / "state.json"
    env = dict(os.environ, PYTHONPATH=f"{ROOT}{os.pathsep}{tmp_path}")

    def cli(*argv):
        proc = subprocess.run(
            [sys.executable, "-m", "jarvis_bots.cli", *argv,
             "--bots", "wiring", "--state", str(state)],
            cwd=str(ROOT), env=env, capture_output=True, text=True,
        )
        assert proc.returncode == 0, proc.stderr
        return proc.stdout

    assert "ticked=1" in cli("round")
    assert "paused restock" in cli("pause", "--id", "restock")
    assert json.loads(cli("status")) == {"attention": 0, "state": "warn"}
    card = json.loads(cli("state"))["bots"][0]
    assert card["id"] == "restock" and card["state"] == "paused"
    assert "resumed restock" in cli("resume", "--id", "restock")
    assert json.loads(cli("status"))["state"] == "ok"


def test_the_boundary_holds_across_every_module_in_the_package():
    """SCOPE: nothing here performs a purchase, a payment or a transaction.

    Checked against the source of every shipped module rather than against
    a promise in a docstring, because the promise is what an added lane
    would keep while adding the call.
    """
    import io
    import tokenize

    banned = re.compile(
        r"^(checkout|add_to_cart|place_order|charge_card|capture_payment|"
        r"submit_payment|purchase|pay|buy_now)$", re.I
    )
    scanned = 0
    for path in sorted((ROOT / "jarvis_bots").rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        scanned += 1
        source = path.read_text(encoding="utf-8")
        # Names only: comments and strings are prose, and the prose in this
        # package is largely *about* not checking out.
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type != tokenize.NAME:
                continue
            assert not banned.match(token.string), (
                f"{path}:{token.start[0]}: {token.string}"
            )
    assert scanned >= 7, f"only scanned {scanned} modules"


