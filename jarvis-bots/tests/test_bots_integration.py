def test_nothing_exported_shadows_a_submodule():
    """``from jarvis_bots import registry`` must always mean the module.

    If the package bound a class or a function under a submodule's name the
    attribute would be one thing before that submodule was imported and
    another after, so the bug would depend on import order.
    """
    assert not jarvis_bots.SUBMODULES.intersection(jarvis_bots.__all__)
    for name in sorted(jarvis_bots.SUBMODULES):
        path = ROOT / "jarvis_bots" / name
        if not path.exists() and not path.with_suffix(".py").exists():
            continue  # a name reserved ahead of the module existing
        assert name not in jarvis_bots.__all__
        assert not hasattr(jarvis_bots, name) or getattr(
            jarvis_bots, name
        ).__class__.__name__ == "module"


