class Clock:
    """The injected clock: it moves when a test moves it, and never else."""

    def __init__(self, at: float = 1_700_000_000.0) -> None:
        self.at = float(at)

    def __call__(self) -> float:
        return self.at

    def advance(self, by: float) -> None:
        self.at += float(by)


class ScriptedBot(BaseBot):
    """A bot whose whole behaviour is a list of (severity, key, resolved).

    Small enough to read, which matters: the point of these tests is what
    the *supervisor* does with what a bot returns, so the bot must not be
    interesting.
    """

    def __init__(self, clock, bot_id: str = "scripted", script=()) -> None:
        super().__init__(
            clock,
            BotInfo(id=bot_id, name=bot_id.title(), blurb="scripted",
                    kind="radar", interval_s=300.0, href=f"/bots/{bot_id}"),
        )
        self._script = list(script)
        self._n = 0

    def tick(self, now):
        step = self._script[self._n] if self._n < len(self._script) else ()
        self._n += 1
        events = []
        for severity, key, resolved in step:
            data = {RESOLVED_FLAG: resolved} if resolved is not None else {}
            events.append(
                self.event(severity, f"{self.id} step {self._n}",
                           attention_key=key, href=self.info.href, **data)
            )
        return events

    def status(self):
        return BotStatus(
            BotState.RUNNING if self._n else BotState.IDLE,
            stats=(self.stat("Ticks", str(self._n)),),
        )


def run_rounds(supervisor: Supervisor, clock: Clock, n: int, step: float = 600.0):
    reports = []
    for _ in range(n):
        reports.append(supervisor.run_round(clock.at))
        clock.advance(step)
    return reports


def demo_state_from_page() -> Dict[str, Any]:
    """``DEMO_STATE`` out of ``bots.html``, as data.

    It is a JavaScript object literal with bare keys, so the keys are
    quoted and then parsed as JSON.  Nothing is executed: the page is read,
    never run.
    """
    text = (WEB / "bots.html").read_text(encoding="utf-8")
    match = re.search(r"const DEMO_STATE = (\{.*?\n\});", text, re.S)
    assert match is not None, "bots.html no longer carries a DEMO_STATE"
    body = re.sub(r"//[^\n]*", "", match.group(1))
    body = re.sub(r"(^|[{,\s])([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', body)
    return json.loads(re.sub(r",(\s*[}\]])", r"\1", body))


def readme_payloads() -> List[Dict[str, Any]]:
    """The JSON blocks ``web/README.md`` documents, in order: badge, page,
    then the per-bot detail payload."""
    text = (WEB / "README.md").read_text(encoding="utf-8")
    return [json.loads(b) for b in re.findall(r"```json\n(.*?)```", text, re.S)]


def json_shape(value: Any) -> Any:
    """An object reduced to its keys and the JSON type of each leaf."""
    if isinstance(value, dict):
        return {k: json_shape(v) for k, v in sorted(value.items())}
    if isinstance(value, list):
        return [json_shape(value[0])] if value else []
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if value is None:
        return "null"
    return "str"


