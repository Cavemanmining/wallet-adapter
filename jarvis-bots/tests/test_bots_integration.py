def test_importing_the_package_reads_no_clock_and_draws_no_randomness():
    """contracts.py: "Time is injected everywhere."

    ``jarvis_bots.cli`` is the composition root and may import ``time``;
    importing the *package* must not, or a bot could reach a wall clock
    without anyone wiring one.
    """
    import ast

    tree = ast.parse((ROOT / "jarvis_bots" / "__init__.py").read_text(encoding="utf-8"))
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module)
    for forbidden in ("time", "random", "socket", "urllib", "urllib.request",
                      "jarvis_bots.cli", "jarvis_bots.validate"):
        assert forbidden not in imported, f"__init__.py imports {forbidden}"
    assert "jarvis_bots.contracts" in imported


