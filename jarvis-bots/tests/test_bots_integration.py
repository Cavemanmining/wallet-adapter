def test_launcher_state_matches_the_readme_key_for_key():
    """``web/README.md`` is the contract the page is written against.

    A key the page does not know is ignored in silence; a key it wants and
    does not get renders as blank.  So the check is on the key *set* and
    the key *order*, both ways.
    """
    badge_doc, page_doc, detail_doc = readme_payloads()
    clock = Clock()
    bot = ScriptedBot(clock, "poke", [[(Severity.ACTION, "k", None)]])
    sup = Supervisor(BotRegistry([bot]), clock)
    sup.run_round(clock.at)

    badge = sup.badge_status()
    assert list(badge) == list(badge_doc)
    assert json_shape(badge) == json_shape(badge_doc)
    assert badge["state"] in {"ok", "warn", "error"}

    page = sup.launcher_state(clock.at)
    assert sorted(page) == sorted(page_doc)
    assert list(page["bots"][0]) == list(page_doc["bots"][0]), "card key order"
    assert json_shape(page["bots"][0]) == json_shape(page_doc["bots"][0])
    assert json.loads(json.dumps(page)) == page

    # The fourth endpoint, which web/README.md documents and
    # jarvis_bots/api.py serves: the card, plus detail, plus the bot's open
    # questions and its recent events.  The generated detail page reads
    # exactly this and nothing in the package could produce it before.
    detail = sup.bot_detail("poke", clock.at)
    assert sorted(detail) == sorted(detail_doc)
    documented = set(detail_doc["bot"]) - {"…"}
    assert documented <= set(detail["bot"]), sorted(documented - set(detail["bot"]))
    for key in ("attention_items", "events"):
        assert json_shape(detail["bot"][key]) == json_shape(detail_doc["bot"][key])
    assert json.loads(json.dumps(detail)) == detail


